// Build step (run by wrangler before every deploy/dev): embeds public/ into the Worker
// as src/generated/site-files.js, so the page is served by the Worker itself.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";

const TYPES = {
  html: "text/html; charset=utf-8", css: "text/css; charset=utf-8",
  js: "text/javascript; charset=utf-8", svg: "image/svg+xml",
};
const files = {};
for (const name of readdirSync("public")) {
  const type = TYPES[name.split(".").pop()];
  if (!type) continue;
  files[`/${name}`] = [readFileSync(`public/${name}`, "utf8"), type];
}
files["/"] = files["/index.html"];
mkdirSync("src/generated", { recursive: true });
writeFileSync("src/generated/site-files.js",
  `// Generated by scripts/embed-site.js - do not edit.\nexport const FILES = ${JSON.stringify(files)};\n`);
console.log(`Embedded ${Object.keys(files).length - 1} files from public/`);
